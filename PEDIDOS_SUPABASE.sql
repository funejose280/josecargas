-- José Recargas: pedidos y seguimiento compartido entre dispositivos.
-- Ejecutar una sola vez en Supabase > SQL Editor > New query.
create table if not exists public.pedidos (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^JR-[A-Z0-9]{6}$'),
  status text not null default 'pendiente' check (status in ('pendiente','proceso','entregado','completado','cancelado')),
  total numeric(12,2) not null check (total >= 0),
  player_id text not null check (player_id ~ '^[0-9]{6,15}$'),
  player_name text,
  products jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.pedidos enable row level security;
-- No se permite listar pedidos directamente desde el navegador.
revoke all on public.pedidos from anon, authenticated;
grant insert (code, status, total, player_id, player_name, products) on public.pedidos to anon, authenticated;

drop policy if exists "Clientes crean pedidos pendientes" on public.pedidos;
create policy "Clientes crean pedidos pendientes" on public.pedidos
for insert to anon, authenticated
with check (
  status = 'pendiente'
  and code ~ '^JR-[A-Z0-9]{6}$'
  and total >= 0
  and player_id ~ '^[0-9]{6,15}$'
  and jsonb_typeof(products) = 'array'
);

-- Función de consulta por código exacto; solo devuelve los campos necesarios al cliente.
create or replace function public.consultar_estado_pedido(codigo_pedido text)
returns table (code text, status text, total numeric, updated_at timestamptz)
language sql
security definer
set search_path = public
as $$
  select p.code, p.status, p.total, p.updated_at
  from public.pedidos p
  where p.code = upper(trim(codigo_pedido))
  limit 1;
$$;
revoke all on function public.consultar_estado_pedido(text) from public;
grant execute on function public.consultar_estado_pedido(text) to anon, authenticated;

-- Mantener updated_at al cambiar el estado desde el panel de Supabase.
create or replace function public.actualizar_pedido_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
drop trigger if exists pedidos_updated_at on public.pedidos;
create trigger pedidos_updated_at before update on public.pedidos
for each row execute function public.actualizar_pedido_updated_at();


-- Historial de compras por ID de jugador.
-- Devuelve únicamente los campos necesarios para mostrar pedidos en la web.
create or replace function public.consultar_historial_pedidos(id_jugador text)
returns table (
  code text,
  status text,
  total numeric,
  products jsonb,
  created_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  select p.code, p.status, p.total, p.products, p.created_at
  from public.pedidos p
  where p.player_id = trim(id_jugador)
  order by p.created_at desc
  limit 50;
$$;
revoke all on function public.consultar_historial_pedidos(text) from public;
grant execute on function public.consultar_historial_pedidos(text) to anon, authenticated;
