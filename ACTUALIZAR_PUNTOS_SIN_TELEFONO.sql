ALTER TABLE public.customer_accounts ALTER COLUMN player_id SET NOT NULL;
ALTER TABLE public.customer_accounts ADD COLUMN IF NOT EXISTS phone text;
ALTER TABLE public.customer_accounts ALTER COLUMN phone DROP NOT NULL;
ALTER TABLE public.customer_accounts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.customer_accounts FROM anon, authenticated;
GRANT SELECT ON public.customer_accounts TO authenticated;
DROP POLICY IF EXISTS "Cliente ve su asociación" ON public.customer_accounts;
CREATE POLICY "Cliente ve su asociación" ON public.customer_accounts
FOR SELECT TO authenticated USING (auth.uid() = user_id);

-- Vincula cuentas actuales por su metadata player_id, sin tocar pedidos ni puntos.
INSERT INTO public.customer_accounts(user_id, player_id)
SELECT u.id, trim(u.raw_user_meta_data->>'player_id')
FROM auth.users u
WHERE NULLIF(trim(u.raw_user_meta_data->>'player_id'), '') IS NOT NULL
ON CONFLICT (user_id) DO UPDATE SET player_id = EXCLUDED.player_id;

-- Al registrarse, guarda la relación de su cuenta con el ID de jugador.
CREATE OR REPLACE FUNCTION public.jr_link_customer_account()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE v_player text;
BEGIN
 v_player := NULLIF(trim(NEW.raw_user_meta_data->>'player_id'), '');
 IF v_player IS NOT NULL THEN
  INSERT INTO public.customer_accounts(user_id, player_id)
  VALUES (NEW.id, v_player)
  ON CONFLICT (user_id) DO UPDATE SET player_id = EXCLUDED.player_id;
 END IF;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_jr_link_customer_account ON auth.users;
CREATE TRIGGER trg_jr_link_customer_account AFTER INSERT OR UPDATE OF raw_user_meta_data ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.jr_link_customer_account();

-- Consulta privada de puntos: toma los totales existentes del ID, sin teléfono.
CREATE OR REPLACE FUNCTION public.jr_my_loyalty_summary()
RETURNS TABLE(linked boolean, points integer, purchase_count integer, total_spent numeric)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, auth AS $$
 SELECT true, cl.points, cl.purchase_count, cl.total_spent
 FROM public.customer_accounts ca
 JOIN public.customer_loyalty cl ON cl.player_id = ca.player_id
 WHERE ca.user_id = auth.uid()
 ORDER BY cl.updated_at DESC LIMIT 1;
$$;
REVOKE ALL ON FUNCTION public.jr_my_loyalty_summary() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.jr_my_loyalty_summary() TO authenticated;

-- Solicitudes de códigos de descuento: el cliente solo puede crear una solicitud elegible.
CREATE TABLE IF NOT EXISTS public.discount_code_requests (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 player_id text NOT NULL,
 points integer NOT NULL,
 purchase_count integer NOT NULL,
 status text NOT NULL DEFAULT 'pendiente' CHECK (status IN ('pendiente','aprobada','entregada','rechazada')),
 discount_code text,
 created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.discount_code_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.discount_code_requests FROM anon, authenticated;
CREATE OR REPLACE FUNCTION public.jr_request_discount_code()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE v_player text; v_points integer; v_count integer; v_id bigint;
BEGIN
 SELECT player_id INTO v_player FROM public.customer_accounts WHERE user_id = auth.uid();
 IF v_player IS NULL THEN RAISE EXCEPTION 'No encontramos el ID de jugador de tu cuenta.'; END IF;
 SELECT points, purchase_count INTO v_points, v_count FROM public.customer_loyalty WHERE player_id = v_player LIMIT 1;
 IF COALESCE(v_points,0) < 50 AND COALESCE(v_count,0) < 5 THEN RAISE EXCEPTION 'Necesitás 50 puntos o 5 compras completadas para solicitar un código.'; END IF;
 IF EXISTS (SELECT 1 FROM public.discount_code_requests WHERE user_id = auth.uid() AND status = 'pendiente') THEN
  RAISE EXCEPTION 'Ya tenés una solicitud pendiente. José te avisará cuando esté lista.';
 END IF;
 INSERT INTO public.discount_code_requests(user_id, player_id, points, purchase_count)
 VALUES(auth.uid(), v_player, COALESCE(v_points,0), COALESCE(v_count,0)) RETURNING id INTO v_id;
 RETURN jsonb_build_object('request_id',v_id,'status','pendiente');
END; $$;
REVOKE ALL ON FUNCTION public.jr_request_discount_code() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.jr_request_discount_code() TO authenticated;

