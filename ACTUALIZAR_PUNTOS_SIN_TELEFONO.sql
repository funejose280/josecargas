-- Cada pedido nuevo puede guardar el usuario autenticado que lo realizó.
ALTER TABLE public.pedidos ADD COLUMN IF NOT EXISTS user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL;
GRANT INSERT (user_id) ON public.pedidos TO authenticated;
DROP POLICY IF EXISTS "Clientes crean pedidos pendientes" ON public.pedidos;
CREATE POLICY "Clientes crean pedidos pendientes" ON public.pedidos
FOR INSERT TO anon, authenticated
WITH CHECK (
 status = 'pendiente' AND code ~ '^JR-[A-Z0-9]{6}$' AND total >= 0
 AND player_id ~ '^[0-9]{6,15}$' AND jsonb_typeof(products) = 'array'
 AND (user_id IS NULL OR user_id = auth.uid())
);

