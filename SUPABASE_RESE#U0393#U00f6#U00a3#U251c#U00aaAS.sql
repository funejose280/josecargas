-- Ejecutá este SQL en Supabase > SQL Editor > New query.
create table if not exists public.resenas (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 2 and 40),
  rating integer not null check (rating between 1 and 5),
  message text not null check (char_length(trim(message)) between 5 and 700),
  created_at timestamptz not null default now()
);

alter table public.resenas enable row level security;

-- Cualquier visitante puede leer las reseñas publicadas.
drop policy if exists "Resenas visibles para todos" on public.resenas;
create policy "Resenas visibles para todos"
on public.resenas for select
to anon, authenticated
using (true);

-- Permite a los visitantes publicar reseñas sin iniciar sesión.
drop policy if exists "Visitantes pueden publicar resenas" on public.resenas;
create policy "Visitantes pueden publicar resenas"
on public.resenas for insert
to anon, authenticated
with check (
  char_length(trim(name)) between 2 and 40
  and rating between 1 and 5
  and char_length(trim(message)) between 5 and 700
);

grant select, insert on public.resenas to anon, authenticated;
grant usage, select on sequence public.resenas_id_seq to anon, authenticated;
